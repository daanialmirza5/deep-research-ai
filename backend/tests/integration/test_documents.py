def _build_minimal_pdf(text: str) -> bytes:
    """See ai/tests/test_loaders.py's identical helper for why this is
    hand-built rather than generated by a library — pypdf has no
    page-writing API of its own."""
    objects = [
        b"<</Type/Catalog/Pages 2 0 R>>",
        b"<</Type/Pages/Kids[3 0 R]/Count 1>>",
        b"<</Type/Page/Parent 2 0 R/Resources<</Font<</F1 4 0 R>>>>"
        b"/MediaBox[0 0 200 200]/Contents 5 0 R>>",
        b"<</Type/Font/Subtype/Type1/BaseFont/Helvetica>>",
    ]
    stream = f"BT /F1 24 Tf 10 100 Td ({text}) Tj ET".encode()
    objects.append(
        b"<</Length " + str(len(stream)).encode() + b">>\nstream\n" + stream + b"\nendstream"
    )

    out = io.BytesIO()
    out.write(b"%PDF-1.4\n")
    offsets = []
    for index, body in enumerate(objects, start=1):
        offsets.append(out.tell())
        out.write(str(index).encode() + b" 0 obj" + body + b"endobj\n")
    xref_offset = out.tell()
    count = len(objects) + 1
    out.write(b"xref\n")
    out.write(f"0 {count}\n".encode())
    out.write(b"0000000000 65535 f \n")
    for offset in offsets:
        out.write(f"{offset:010d} 00000 n \n".encode())
    out.write(b"trailer\n")
    out.write(f"<</Size {count}/Root 1 0 R>>\n".encode())
    out.write(b"startxref\n" + str(xref_offset).encode() + b"\n%%EOF")
    return out.getvalue()


async def _process(document_id: str) -> None:
    await tasks_module._process_document_async(uuid.UUID(document_id))


async def test_every_source_type_uploads_or_imports_and_becomes_searchable(
    client: TestClient,
) -> None:
    email, password = _unique_email(), "correct-horse-battery-staple"
    resp = client.post(
        "/api/v1/auth/register",
        json={"email": email, "password": password, "full_name": "Docs Tester"},
    )
    assert resp.status_code == 201, resp.text
    resp = client.post("/api/v1/auth/login", json={"email": email, "password": password})
    assert resp.status_code == 200, resp.text
    headers = {"Authorization": f"Bearer {resp.json()['access_token']}"}

    resp = client.post("/api/v1/projects", json={"name": "Docs Test Project"}, headers=headers)
    assert resp.status_code == 201, resp.text
    project_id = resp.json()["id"]

    docx_buffer = io.BytesIO()
    docx_document = docx.Document()
    docx_document.add_paragraph(
        "Photosynthesis converts sunlight into chemical energy stored in plants."
    )
    docx_document.save(docx_buffer)

    uploads = [
        (
            "report.pdf",
            _build_minimal_pdf("The mitochondria is the powerhouse of the cell"),
            "application/pdf",
        ),
        (
            "notes.docx",
            docx_buffer.getvalue(),
            "application/vnd.openxmlformats-officedocument.wordprocessingml.document",
        ),
        (
            "plain.txt",
            b"The Great Wall of China stretches across northern China for thousands of miles.",
            "text/plain",
        ),
        ("data.csv", b"planet,distance_au\nMercury,0.39\nVenus,0.72\n", "text/csv"),
        (
            "readme.md",
            b"# Volcanoes\n\nVolcanoes form where magma reaches the Earth's surface.",
            "text/markdown",
        ),
    ]

    document_ids: dict[str, str] = {}
    for filename, content, content_type in uploads:
        with patch("app.api.v1.documents.celery_app.send_task") as send_task:
            resp = client.post(
                "/api/v1/documents/upload",
                data={"project_id": project_id},
                files={"file": (filename, content, content_type)},
                headers=headers,
            )
        assert resp.status_code == 201, resp.text
        body = resp.json()
        assert body["status"] == "pending"
        send_task.assert_called_once_with("knowledge_base.process_document", args=[body["id"]])
        await _process(body["id"])
        document_ids[filename] = body["id"]

    url_source = "https://example.com"
    youtube_source = "https://www.youtube.com/watch?v=jNQXAC9IdLA"
    for url, expected_source_type in ((url_source, "url"), (youtube_source, "youtube")):
        with patch("app.api.v1.documents.celery_app.send_task"):
            resp = client.post(
                "/api/v1/documents/import-url",
                json={"project_id": project_id, "url": url},
                headers=headers,
            )
        assert resp.status_code == 201, resp.text
        body = resp.json()
        assert body["source_type"] == expected_source_type
        document_ids[url] = body["id"]

    await _process(document_ids[url_source])
    try:
        await _process(document_ids[youtube_source])
        youtube_processed = True
    except Exception:  # noqa: BLE001 - YouTube transcript fetch is a live, rate-limit-prone dependency
        youtube_processed = False

    reliable_documents = {k: v for k, v in document_ids.items() if k != youtube_source}
    for name, document_id in reliable_documents.items():
        resp = client.get(f"/api/v1/documents/{document_id}", headers=headers)
        assert resp.status_code == 200, resp.text
        assert resp.json()["status"] == "indexed", f"{name} did not index: {resp.json()}"

    if youtube_processed:
        resp = client.get(f"/api/v1/documents/{document_ids[youtube_source]}", headers=headers)
        assert resp.json()["status"] == "indexed"

    resp = client.get(
        "/api/v1/knowledge-base/search",
        params={"project_id": project_id, "q": "powerhouse of the cell", "top_k": 5},
        headers=headers,
    )
    assert resp.status_code == 200, resp.text
    results = resp.json()
    assert any("mitochondria" in r["chunk_text"].lower() for r in results)

    resp = client.get(f"/api/v1/projects/{project_id}/documents", headers=headers)
    assert resp.status_code == 200, resp.text
    listed = resp.json()
    assert len(listed) == len(document_ids)
    for entry in listed:
        if entry["status"] == "indexed":
            assert entry["chunk_count"] >= 1

    pdf_document_id = document_ids["report.pdf"]
    resp = client.delete(f"/api/v1/documents/{pdf_document_id}", headers=headers)
    assert resp.status_code == 204
    resp = client.get(f"/api/v1/documents/{pdf_document_id}", headers=headers)
    assert resp.status_code == 404


