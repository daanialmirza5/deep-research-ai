    client.post(
        "/api/v1/auth/register",
        json={"email": email, "password": password, "full_name": "Docs Tester"},
    )
    resp = client.post("/api/v1/auth/login", json={"email": email, "password": password})
    headers = {"Authorization": f"Bearer {resp.json()['access_token']}"}

    other_email, other_password = _unique_email(), "correct-horse-battery-staple"
    client.post(
        "/api/v1/auth/register",
        json={"email": other_email, "password": other_password, "full_name": "Other"},
    )
    resp = client.post(
        "/api/v1/auth/login", json={"email": other_email, "password": other_password}
    )
    other_headers = {"Authorization": f"Bearer {resp.json()['access_token']}"}

    resp = client.post(
        "/api/v1/projects", json={"name": "Not Yours"}, headers=other_headers
    )
    other_project_id = resp.json()["id"]

    resp = client.post(
        "/api/v1/documents/upload",
        data={"project_id": other_project_id},
        files={"file": ("notes.txt", b"hello", "text/plain")},
        headers=headers,
    )
    assert resp.status_code == 404
